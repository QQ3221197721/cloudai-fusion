// WithCompilationCache returns cfg with a fresh in-memory wazero.CompilationCache
// attached. Sharing it across sandboxes lets the second-and-later compilation of
// identical module bytes reuse the already-generated native code instead of
// recompiling — the honest precompiled-binary-cache optimization exercised by
// BenchmarkM42_FLIP_ColdStart_Ours_Cached.
func WithCompilationCache(cfg RuntimeConfig) RuntimeConfig {
	cfg.CompilationCache = wazero.NewCompilationCache()
	return cfg
}

