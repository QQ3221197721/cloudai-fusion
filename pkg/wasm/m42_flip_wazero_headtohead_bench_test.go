// leb128u encodes an unsigned integer as unsigned LEB128. For the small,
// non-negative constants used here (< 2^21) this also equals the signed LEB128
// encoding, which is what the i32.const immediate requires.
func leb128u(v uint32) []byte {
	var out []byte
	for {
		b := byte(v & 0x7f)
		v >>= 7
		if v != 0 {
			out = append(out, b|0x80)
		} else {
			out = append(out, b)
			return out
		}
	}
}

// wasmSection wraps a section body with its id and computed LEB128 size.
func wasmSection(id byte, body []byte) []byte {
	out := []byte{id}
	out = append(out, leb128u(uint32(len(body)))...)
	return append(out, body...)
}

// buildFuncModule assembles a valid WASM module exporting func "f"(i32,i32)->i32.
// The body computes: (arg0 <op> arg1) [+ konst if konst>0]. All section sizes are
// computed from the actual payloads, so every produced binary is spec-valid.
func buildFuncModule(op byte, konst uint32) []byte {
	// Function body opcodes.
	body := []byte{0x20, 0x00, 0x20, 0x01, op} // local.get 0; local.get 1; <op>
	if konst > 0 {
		body = append(body, 0x41)             // i32.const
		body = append(body, leb128u(konst)...) // <konst>
		body = append(body, 0x6a)             // i32.add
	}
	body = append(body, 0x0b) // end

	// Code entry = vec(locals)=0 followed by the body, prefixed by its size.
	codeEntry := append([]byte{0x00}, body...)
	codeEntry = append(leb128u(uint32(len(codeEntry))), codeEntry...)
	codeSecBody := append([]byte{0x01}, codeEntry...) // count = 1 function

	// Export "f" as function index 0.
	name := "f"
	expEntry := append([]byte{byte(len(name))}, []byte(name)...)
	expEntry = append(expEntry, 0x00, 0x00) // kind=func(0x00), func index 0
	expSecBody := append([]byte{0x01}, expEntry...) // count = 1 export

	typeSecBody := []byte{0x01, 0x60, 0x02, 0x7f, 0x7f, 0x01, 0x7f} // 1 type: (i32,i32)->i32
	funcSecBody := []byte{0x01, 0x00}                               // 1 func, type index 0

	out := []byte{0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00} // \0asm + version 1
	out = append(out, wasmSection(0x01, typeSecBody)...)          // Type
	out = append(out, wasmSection(0x03, funcSecBody)...)          // Function
	out = append(out, wasmSection(0x07, expSecBody)...)           // Export
	out = append(out, wasmSection(0x0a, codeSecBody)...)          // Code
	return out
}

type genModule struct {
	bytes  []byte
	op     byte
	konst  uint32
	expect uint32 // expected result of f(3,5)
}

// generateModuleFamily creates 128 distinct valid modules across 4 op families
// (add/sub/mul/add-with-const) × 32 constant parameterizations.
func generateModuleFamily() []genModule {
	ops := []struct {
		code byte
		eval func(a, b, k uint32) uint32
	}{
		{0x6a, func(a, b, k uint32) uint32 { return a + b + k }},        // i32.add
		{0x6b, func(a, b, k uint32) uint32 { return a - b + k }},        // i32.sub
		{0x6c, func(a, b, k uint32) uint32 { return a*b + k }},          // i32.mul
		{0x6a, func(a, b, k uint32) uint32 { return a + b + k }},        // add family (distinct via konst)
	}
	mods := make([]genModule, 0, 128)
	for oi, op := range ops {
		for i := 0; i < 32; i++ {
			konst := uint32(0)
			if oi == 3 {
				konst = uint32((i + 1) * 7) // 7..224, forces i32.const path
			}
			mods = append(mods, genModule{
				bytes:  buildFuncModule(op.code, konst),
				op:     op.code,
				konst:  konst,
				expect: op.eval(3, 5, konst),
			})
		}
	}
	return mods
}

var moduleFamily = generateModuleFamily()

// familyBytes returns just the raw binaries (helper for benchmarks).
func familyBytes() [][]byte {
	out := make([][]byte, len(moduleFamily))
	for i, m := range moduleFamily {
		out[i] = m.bytes
	}
	return out
}

var wasmModuleFamily = familyBytes()

// ============================================================================
// CORRECTNESS PROOF: every generated module compiles AND computes correctly
// ============================================================================

func TestM42_FLIP_DatasetValidity(t *testing.T) {
	ctx := context.Background()
	rt := wazero.NewRuntimeWithConfig(ctx, wazero.NewRuntimeConfig().WithMemoryLimitPages(100))
	defer rt.Close(ctx)

	if len(moduleFamily) != 128 {
		t.Fatalf("expected 128 modules, got %d", len(moduleFamily))
	}

	for idx, m := range moduleFamily {
		compiled, err := rt.CompileModule(ctx, m.bytes)
		if err != nil {
			t.Fatalf("module %d failed to compile: %v (bytes=%x)", idx, err, m.bytes)
		}
		mod, err := rt.InstantiateModule(ctx, compiled, wazero.NewModuleConfig().WithName(fmt.Sprintf("m%d", idx)))
		if err != nil {
			t.Fatalf("module %d failed to instantiate: %v", idx, err)
		}
		fn := mod.ExportedFunction("f")
		if fn == nil {
			t.Fatalf("module %d: export \"f\" missing", idx)
		}
		res, err := fn.Call(ctx, 3, 5)
		if err != nil || len(res) != 1 {
			t.Fatalf("module %d: call failed: res=%v err=%v", idx, res, err)
		}
		if uint32(res[0]) != m.expect {
			t.Fatalf("module %d: op=0x%x konst=%d got f(3,5)=%d want %d", idx, m.op, m.konst, uint32(res[0]), m.expect)
		}
		_ = mod.Close(ctx)
	}
	t.Logf("all %d generated modules compiled and produced correct arithmetic results", len(moduleFamily))
}

