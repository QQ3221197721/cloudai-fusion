// Evaluate checks event against all enabled rules and returns matching alerts
func (de *DetectionEngine) Evaluate(event map[string]interface{}) []*AlertEvent {
	var alerts []*AlertEvent
	
	for id, rule := range de.rules {
		if !de.enabledRules[id] {
			continue
		}
		
		if de.matchesRule(rule, event) {
			alert := de.createAlert(rule, event)
			alerts = append(alerts, alert)
			
			if len(alerts) >= de.config.MaxAlertsPerEvent {
				break
			}
		}
	}
	
	return alerts
}

// matchesRule performs pattern matching against rule logic
func (de *DetectionEngine) matchesRule(rule DetectionRule, event map[string]interface{}) bool {
	logic := strings.ToLower(rule.DetectionLogic)
	
	// Extract relevant fields from event
	var eventStr string
	for key, value := range event {
		eventStr += fmt.Sprintf("%s=%v ", key, value)
	}
	
	// Simple keyword matching for syslog-style detection
	if strings.Contains(logic, "contains") || strings.Contains(logic, "match") {
		pattern := extractRegexFromDetection(logic)
		if pattern != "" {
			re, err := regexp.Compile(pattern)
			if err == nil && re.MatchString(eventStr) {
				return true
			}
		}
	}
	
	// Check specific conditions
	if strings.Contains(logic, "syslog contains \"stack smashing detected\"") &&
		strings.Contains(eventStr, "stack smashing detected") {
		return true
	}
	
	if strings.Contains(logic, "segfault") &&
		strings.Contains(eventStr, "segfault") {
		return true
	}
	
	if strings.Contains(logic, "overflow") &&
		strings.Contains(eventStr, "overflow") {
		return true
	}
	
	return false
}

// extractRegexFromDetection pulls regex pattern from detection logic
func extractRegexFromDetection(detectionLogic string) string {
	re := regexp.MustCompile(`"(.*?)"`)
	matches := re.FindAllStringSubmatch(detectionLogic, -1)
	if len(matches) > 0 {
		return matches[0][1]
	}
	return ""
}

// GetRule returns specific rule by ID
func (de *DetectionEngine) GetRule(ruleID string) (DetectionRule, bool) {
	rule, exists := de.rules[ruleID]
	return rule, exists
}

// GetAllRules returns all registered rules
func (de *DetectionEngine) GetAllRules() []DetectionRule {
	rules := make([]DetectionRule, 0, len(de.rules))
	for _, rule := range de.rules {
		rules = append(rules, rule)
	}
	return rules
}

// EnableRule activates a specific detection rule
func (de *DetectionEngine) EnableRule(ruleID string) error {
	rule, exists := de.rules[ruleID]
	if !exists {
		return fmt.Errorf("rule not found: %s", ruleID)
	}
	
	de.enabledRules[ruleID] = true
	rule.Status = StatusActive
	de.rules[ruleID] = rule
	return nil
}

// DisableRule deactivates a specific detection rule
func (de *DetectionEngine) DisableRule(ruleID string) error {
	rule, exists := de.rules[ruleID]
	if !exists {
		return fmt.Errorf("rule not found: %s", ruleID)
	}
	
	de.enabledRules[ruleID] = false
	rule.Status = StatusDisabled
	de.rules[ruleID] = rule
	return nil
}

// AddDynamicRule registers custom dynamic detection logic
func (de *DetectionEngine) AddDynamicRule(id string, predicate func(event map[string]interface{}) bool) error {
	if _, exists := de.rules[id]; exists {
		return fmt.Errorf("rule already exists: %s", id)
	}
	
	de.dynamicRules[id] = predicate
	
	rule := DetectionRule{
		ID:       id,
		Name:     fmt.Sprintf("Dynamic Rule: %s", id),
		Status:   StatusActive,
		IsAutoGenerated: true,
	}
	de.rules[id] = rule
	de.enabledRules[id] = true
	
	return nil
}

