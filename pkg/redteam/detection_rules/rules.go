// DetectionEngine evaluates events against registered rules
type DetectionEngine struct {
	rules          map[string]DetectionRule
	dynamicRules   map[string]func(event map[string]interface{}) bool
	alertHistory   []*AlertEvent
	enabledRules   map[string]bool
	config         *EngineConfig
}

// EngineConfig configures detection engine behavior
type EngineConfig struct {
	DefaultSeverity     Severity
	MaxAlertsPerEvent   int
	EnableMITREMapping  bool
	ComplianceProfiles  []string // PCI-DSS, HIPAA, NIST, SOC2
	AlertThrottling     bool
	ThrottleWindow      time.Duration
	NotificationChannels []string // email, slack, pagerduty, siem
}

// DefaultEngineConfig returns safe defaults for production use
func DefaultEngineConfig() *EngineConfig {
	return &EngineConfig{
		DefaultSeverity:      Medium,
		MaxAlertsPerEvent:    100,
		EnableMITREMapping:   true,
		ComplianceProfiles:   []string{"PCI-DSS", "NIST"},
		AlertThrottling:      true,
		ThrottleWindow:       5 * time.Minute,
		NotificationChannels: []string{},
	}
}

// NewDetectionEngine creates new detection engine with specified configuration
func NewDetectionEngine(config *EngineConfig) *DetectionEngine {
	if config == nil {
		config = DefaultEngineConfig()
	}
	
	engine := &DetectionEngine{
		rules:          make(map[string]DetectionRule),
		dynamicRules:   make(map[string]func(event map[string]interface{}) bool),
		alertHistory:   make([]*AlertEvent, 0),
		enabledRules:   make(map[string]bool),
		config:         config,
	}
	
	// Load built-in rules
	engine.LoadBuiltInRules()
	
	return engine
}

// DefaultNewDetectionEngine returns legacy-compatible instance
func DefaultNewDetectionEngine() *DetectionEngine {
	return NewDetectionEngine(nil)
}

