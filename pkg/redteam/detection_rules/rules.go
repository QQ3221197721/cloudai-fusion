// ComplianceReport generates compliance mapping report
func (de *DetectionEngine) ComplianceReport() map[string][]string {
	report := make(map[string][]string)
	
	for _, profileStr := range de.config.ComplianceProfiles {
		report[profileStr] = make([]string, 0)
	}
	
	for id, rule := range de.rules {
		if rule.ComplianceTags != nil {
			for profileKey := range rule.ComplianceTags {
				report[profileKey] = append(report[profileKey], id)
			}
		} else {
			report["PCI-DSS"] = append(report["PCI-DSS"], id)
			report["NIST"] = append(report["NIST"], id)
		}
	}
	
	return report
}

