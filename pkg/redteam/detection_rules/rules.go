// addRule registers a single rule in the engine
func (de *DetectionEngine) addRule(rule DetectionRule) {
	de.rules[rule.ID] = rule
	de.enabledRules[rule.ID] = true
}

// createAlert generates alert from matched rule
func (de *DetectionEngine) createAlert(rule DetectionRule, event map[string]interface{}) *AlertEvent {
	alert := &AlertEvent{
		RuleID:        rule.ID,
		RuleName:      rule.Name,
		Timestamp:     time.Now(),
		Severity:      rule.Severity,
		AlertCategory: rule.RuleCategory,
		Description:   rule.Description,
		EventData:     event,
		Evidence:      fmt.Sprintf("%v", event),
		MITREATTK:     rule.MITREATTK,
	}
	
	// Extract common fields from event
	if srcIP, ok := event["source_ip"].(string); ok {
		alert.SourceIP = srcIP
	}
	if dstIP, ok := event["destination_ip"].(string); ok {
		alert.DestinationIP = dstIP
	}
	if user, ok := event["user"].(string); ok {
		alert.User = user
	}
	
	// Add mitigation guidance
	alert.Mitigation = de.getMitigationGuide(rule)
	
	// Add response action
	alert.ResponseAction = de.getResponseAction(rule.Severity)
	
	de.alertHistory = append(de.alertHistory, alert)
	
	return alert
}

