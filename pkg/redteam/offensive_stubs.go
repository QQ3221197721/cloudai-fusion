// selectTemplate selects an exploit template by type
func (edf *ExploitDevelopmentFramework) selectTemplate(vulnType string) *ExploitTemplate {
	for i := range edf.templateLib {
		if edf.templateLib[i].Type == vulnType {
			return &edf.templateLib[i]
		}
	}
	if len(edf.templateLib) > 0 {
		return &edf.templateLib[0]
	}
	return &ExploitTemplate{}
}

