// phenotypeFromGenome derives phenotype (behavior) from genome encoding
func (g Genome) phenotypeFromGenome() AttackStrategy {
	return AttackStrategy{
		Name:               "evolved_strategy",
		Description:        "Strategy derived from genome",
		SuccessProbability: avgWeight(g.ResourceWeights),
		RiskFactor:         g.DetectionAvoidance,
		EffortRequired:     5,
		ToolsNeeded:        make([]ToolConfig, 0),
	}
}

// recordGenerationStats records statistics for the current generation
func (e *AdaptiveHuntEngine) recordGenerationStats(fitnesses []float64) EvolutionGeneration {
	return EvolutionGeneration{
		GenerationNumber: e.currentGen,
		AverageFitness:   averageFitness(fitnesses),
		BestFitness:      maxFitness(fitnesses),
		PopulationSize:   len(e.agentPool),
	}
}

// buildAttackScenario creates an attack scenario from the best agent
func buildAttackScenario(agent *ThreatAgent) *AttackScenario {
	return &AttackScenario{
		ID:          agent.ID + "_scenario",
		Name:        agent.Phenotype.Name,
		Description: agent.Phenotype.Description,
		Strategy:    agent.Phenotype,
		Score:       agent.FitnessScore,
		Risk:        agent.Phenotype.RiskFactor,
		GeneratedAt: time.Now(),
	}
}

