// calculateInitialFitness computes initial fitness score for a new agent strategy
func (e *AdaptiveHuntEngine) calculateInitialFitness(strategy AttackStrategy) float64 {
	baseFitness := strategy.SuccessProbability * 50.0
	riskPenalty := strategy.RiskFactor * 10.0
	return baseFitness - riskPenalty + 25.0
}

// mergeStrategies combines two attack strategies into a child strategy
func mergeStrategies(s1, s2 AttackStrategy) AttackStrategy {
	merged := AttackStrategy{
		Name:               s1.Name + "_x_" + s2.Name,
		Description:        s1.Description,
		SuccessProbability: (s1.SuccessProbability + s2.SuccessProbability) / 2.0,
		RiskFactor:         (s1.RiskFactor + s2.RiskFactor) / 2.0,
		EffortRequired:     (s1.EffortRequired + s2.EffortRequired) / 2,
	}
	// Merge phase order from both parents
	if len(s1.PhaseOrder) > len(s2.PhaseOrder) {
		merged.PhaseOrder = s1.PhaseOrder
	} else {
		merged.PhaseOrder = s2.PhaseOrder
	}
	// Combine tools from both strategies
	merged.ToolsNeeded = append(s1.ToolsNeeded, s2.ToolsNeeded...)
	merged.Dependencies = append(s1.Dependencies, s2.Dependencies...)
	return merged
}

// GenerateUUID generates a simple UUID string
func GenerateUUID() string {
	b := make([]byte, 16)
	_, _ = time.Now().UnixNano(), 0
	for i := range b {
		b[i] = byte(time.Now().UnixNano()>>(i*4)) ^ byte(i*17+3)
	}
	return fmt.Sprintf("%08x-%04x-%04x-%04x-%012x",
		b[0:4], b[4:6], b[6:8], b[8:10], b[10:16])
}
