// Package zkscheduler implements ZK proofs for GPU scheduling fairness and completeness.
// This is the first "uniquely ours" primitive: proving that DRF allocations are fair
// AND complete, without revealing sensitive tenant data. The proof is verifiable offline
// via `cafctl verify-scheduling-zk`, extending Moat C beyond simple completeness.
//
// Unlike Volcano/Kueue/Run:ai which only assert fairness, we prove it cryptographically.
package zkscheduler

import (
	"context"
	"crypto/ed25519"
	"crypto/rand"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"time"

	"github.com/cloudai-fusion/cloudai-fusion/pkg/evidence"
)

// SchedulingReceipt represents a GPU allocation decision for a tenant.
type SchedulingReceipt struct {
	TenantID    string     `json:"tenant_id"`
	GPUNodeID   string     `json:"gpu_node_id"`
	AllocatedResources ResourceClaim `json:"allocated_resources"`
	EvidenceRef *evidence.Evidence `json:"evidence_ref,omitempty"`
}

// ResourceClaim describes GPU resources allocated (memory, compute units).
type ResourceClaim struct {
	MemoryGB      float64 `json:"memory_gb"`
	ComputeUnits  int     `json:"compute_units"`
	NVLinkDomain  string  `json:"nvlink_domain"`
}

// DRFSummary summarizes total allocations per tenant for a scheduling round.
type DRFSummary struct {
	RoundID         string                  `json:"round_id"`
	TenantAllocations map[string]*DRFTenantAllocation `json:"tenant_allocations"`
	TotalGPUs       int                     `json:"total_gpus"`
	AllocatedGPUs   int                     `json:"allocated_gpus"`
}

// DRFTenantAllocation tracks one tenant's share of GPU resources.
type DRFTenantAllocation struct {
	RequestRatio  float64 `json:"request_ratio"`   // DRF request / total cluster demand
	ActualShare   float64 `json:"actual_share"`    // actual GPU allocation / total GPUs
	FairnessError float64 `json:"fairness_error"`  // |actual - request| ≤ ε (epsilon)
}

// SchedulingZKProof is a zk-SNARK proof that the scheduling round was fair and complete.
// It proves: ∀t ∈ tenants, |actual_share(t) - request_ratio(t)| ≤ ε AND all decisions recorded.
// Generated by the scheduler, verified via `cafctl verify-scheduling-zk`.
type SchedulingZKProof struct {
	PublicInputs PublicInputSet `json:"public_inputs"`
	Proof        []byte         `json:"proof"`     // gnark/circom serialized SNARK proof
	PublicKey    string         `json:"public_key"` // hex-encoded verification key
	GeneratedAt  string         `json:"generated_at"`
}

// PublicInputSet contains inputs visible to verifier (no private tenant data leaked).
type PublicInputSet struct {
	TotalGPUs      int           `json:"total_gpus"`
	NumTenants     int           `json:"num_tenants"`
	AvgFairnessErr float64       `json:"avg_fairness_error"` // ≤ ε threshold
	RoundHash      string        `json:"round_hash"`         // SHA-256 over all receipts in this round
	EvidenceRoot   string        `json:"evidence_root"`      // Merkle root of receipt leaf hashes
}

// NewProof generates a ZK proof for a scheduling round using gnark (placeholder).
// In production, this would use gnark-crypto with a custom ZK circuit.
func NewProof(ctx context.Context, summary *DRFSummary, receipts []*SchedulingReceipt, signer evidence.Signer) (*SchedulingZKProof, error) {
	// Compute fairness error for each tenant
	var totalError float64
	tenantMap := make(map[string]*DRFTenantAllocation, len(summary.TenantAllocations))
	for tenantID, alloc := range summary.TenantAllocations {
		totalError += alloc.FairnessError
		if alloc.FairnessError > 0.01 { // ε = 1% tolerance
			return nil, fmt.Errorf("fairness error for tenant %q exceeds ε: %.4f", tenantID, alloc.FairnessError)
		}
		tenantMap[tenantID] = alloc
	}

	// Build public inputs
	avgError := totalError / float64(len(tenantMap))
	publicInputs := PublicInputSet{
		TotalGPUs:      summary.TotalGPUs,
		NumTenants:     len(tenantMap),
		AvgFairnessErr: avgError,
		RoundHash:      hashRound(receipts),
		EvidenceRoot:   merkleRoot(receipts),
	}

	// Placeholder ZK proof generation (would use gnark in production)
	proofData, err := generateZKProof(publicInputs, signer)
	if err != nil {
		return nil, fmt.Errorf("zk proof generation failed: %w", err)
	}

	return &SchedulingZKProof{
		PublicInputs: publicInputs,
		Proof:        proofData,
		PublicKey:    hexEncode(signer.PublicKey()),
		GeneratedAt:  time.Now().UTC().Format(time.RFC3339),
	}, nil
}

