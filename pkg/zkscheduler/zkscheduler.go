// Helper functions (placeholders for production gnark implementation)
func hashRound(receipts []*SchedulingReceipt) string {
	h := sha256.New()
	for _, r := range receipts {
		jsonBytes, _ := json.Marshal(r)
		h.Write(jsonBytes)
	}
	return hex.EncodeToString(h.Sum(nil))
}

func merkleRoot(receipts []*SchedulingReceipt) string {
	// Simplified merkle root (would use proper merkle tree in production)
	if len(receipts) == 0 {
		return ""
	}
	h := sha256.New()
	for _, r := range receipts {
		jsonBytes, _ := json.Marshal(r)
		h.Write(jsonBytes)
	}
	return hex.EncodeToString(h.Sum(nil))
}

