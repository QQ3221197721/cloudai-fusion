// =============================================================================
// M45 / T2 HEAD-TO-HEAD BENCHMARK: Streaming Mahalanobis vs sklearn IF / LOF
// =============================================================================
//
// WORK UNIT (SHARED): Process N labeled multivariate vectors, produce an anomaly
//   score for each vector, then compute F1-score and AUC-ROC on the test region
//   [warmup, n).
//
// FAIRNESS DESIGN:
//  1. ONE SOURCE OF TRUTH: dataset generated by GenerateDataset().
//  2. Shared CSV: both the Go streaming detector AND the Python competitor read
//     EXACTLY the same CSV file (no separate generation).
//  3. Causal scoring: the streaming detector scores x[i] using only x[0..i-1],
//     mirroring real-time operation.
//  4. Batch oracle: sklearn trains on [0, train_end) and scores the test region
//     (generous — trained on "future" relative to the streaming causality).
//  5. count=6 median: reduces variance from hardware noise / warmup.
//  6. HONEST VERDICT: if sklearn wins we explicitly report LOSS with the margin.
//
// USAGE: go test ./pkg/anomaly/ -run TestT2HeadToHead -count=6 -v
// OUTPUT: output/m45_flip_bench.json + console summary with MEDIAN numbers.
// =============================================================================

// benchMetric is the JSON-serialisable per-method result record.
type benchMetric struct {
	Method          string  `json:"method"`
	Description     string  `json:"description"`
	Dim             int     `json:"dimension"`
	Samples         int     `json:"samples"`
	AnomalyRate     float64 `json:"anomaly_rate"`
	AvgLatencyNs    float64 `json:"avg_latency_ns_per_vec"`
	StdLatencyNs    float64 `json:"std_latency_ns_per_vec"`
	MedianLatencyNs float64 `json:"median_latency_ns"`
	ThroughputVs    float64 `json:"throughput_vectors_per_sec"`
	F1Score         float64 `json:"f1_score"`
	AUCROC          float64 `json:"auc_roc"`
	Repetitions     int     `json:"repetitions"`
}

// streamingResult carries the raw measurements from the streaming benchmark.
type streamingResult struct {
	perRepLatency []float64 // mean ns/vec for each repetition
	f1            float64   // F1 on the test region (causal, first rep)
	testScores    []float64 // scores over the test region (for AUC)
}

func TestT2HeadToHead(t *testing.T) {
	t.Logf("==========================================================")
	t.Logf("M45/T2 HEAD-TO-HEAD: CloudAI Streaming vs sklearn Baseline")
	t.Logf("==========================================================")

	// --- Configuration -------------------------------------------------------
	scn := ScenarioCorrelationFlip // canonical JOINT anomaly scenario
	d := 10
	seedCount := 6
	repetitions := 6
	anomFraction := 0.10
	rho := 0.75
	warmup := 800
	total := 3000

	t.Logf("Configuration: scenario=CorrelationFlip d=%d seeds=%d reps=%d anom=%.0f%% rho=%.2f warmup=%d total=%d",
		d, seedCount, repetitions, anomFraction*100, rho, warmup, total)

	tmpDir := t.TempDir()
	dataCSV := filepath.Join(tmpDir, "t2_shared_dataset.csv")
	pythonScript := filepath.Join("testdata", "sklearn_t2_competitor.py")
	pythonAvailable := detectPython(t)

	reports := make([]benchMetric, 0, seedCount*2)

	for seedIdx := 0; seedIdx < seedCount; seedIdx++ {
		seed := int64(seedIdx)
		t.Logf("[%d/%d] Generating dataset seed=%d ...", seedIdx+1, seedCount, seed)

		ds := GenerateDataset(scn, d, total, warmup, anomFraction, rho, seed)
		if err := saveDatasetToCSV(dataCSV, ds); err != nil {
			t.Fatalf("failed to write shared CSV: %v", err)
		}

		// --- Go streaming detector -------------------------------------------
		sr := benchStreamingWithReps(ds, d, repetitions)
		testLabels := ds.Y[warmup:]
		ourMetric := benchMetric{
			Method:          "streaming_mahalanobis",
			Description:     "O(d^2) online Ledoit-Wolf Mahalanobis (CloudAI Fusion)",
			Dim:             d,
			Samples:         len(testLabels),
			AnomalyRate:     fractionTrue(testLabels),
			AvgLatencyNs:    mean(sr.perRepLatency),
			StdLatencyNs:    stdDev(sr.perRepLatency),
			MedianLatencyNs: median(sr.perRepLatency),
			ThroughputVs:    float64(len(testLabels)) / (mean(sr.perRepLatency) / 1e9),
			F1Score:         sr.f1,
			AUCROC:          computeAUC(sr.testScores, testLabels),
			Repetitions:     repetitions,
		}
		reports = append(reports, ourMetric)
		t.Logf("[%d/%d] streaming: median=%.0f ns/vec F1=%.3f AUC=%.3f",
			seedIdx+1, seedCount, ourMetric.MedianLatencyNs, ourMetric.F1Score, ourMetric.AUCROC)

		// --- Competitor ------------------------------------------------------
		if pythonAvailable {
			if m, ok := runSklearnCompetitor(t, pythonScript, dataCSV, d, warmup, len(testLabels), repetitions); ok {
				reports = append(reports, m)
				t.Logf("[%d/%d] sklearn IF: median=%.0f ns/vec F1=%.3f AUC=%.3f",
					seedIdx+1, seedCount, m.MedianLatencyNs, m.F1Score, m.AUCROC)
				continue
			}
			t.Logf("[%d/%d] sklearn subprocess failed, falling back to gonum baseline", seedIdx+1, seedCount)
		}
		// Fallback: batch-covariance Mahalanobis retrain baseline (clearly labeled).
		m := benchBatchMahalanobisBaseline(ds, d, repetitions, warmup)
		reports = append(reports, m)
		t.Logf("[%d/%d] batch-Mahalanobis baseline: median=%.0f ns/vec F1=%.3f AUC=%.3f",
			seedIdx+1, seedCount, m.MedianLatencyNs, m.F1Score, m.AUCROC)
	}

	// --- Aggregate -----------------------------------------------------------
	type agg struct {
		latencyMedians []float64
		f1s            []float64
		aucs           []float64
	}
	aggs := make(map[string]*agg)
	descByMethod := make(map[string]string)
	for _, m := range reports {
		if aggs[m.Method] == nil {
			aggs[m.Method] = &agg{}
		}
		aggs[m.Method].latencyMedians = append(aggs[m.Method].latencyMedians, m.MedianLatencyNs)
		aggs[m.Method].f1s = append(aggs[m.Method].f1s, m.F1Score)
		aggs[m.Method].aucs = append(aggs[m.Method].aucs, m.AUCROC)
		descByMethod[m.Method] = m.Description
	}

	t.Logf("")
	t.Logf("AGGREGATED RESULTS (%d seeds, %d reps each) — MEDIAN across seeds:", seedCount, repetitions)
	t.Logf("%-28s %14s %10s %10s", "METHOD", "LATENCY(ns/vec)", "F1", "AUC")
	for method, a := range aggs {
		t.Logf("%-28s %14.0f %10.3f %10.3f",
			method, median(a.latencyMedians), median(a.f1s), median(a.aucs))
	}

	// --- Verdict -------------------------------------------------------------
	verdict := "INCOMPLETE"
	our := aggs["streaming_mahalanobis"]
	var competitorKey string
	for k := range aggs {
		if k != "streaming_mahalanobis" {
			competitorKey = k
			break
		}
	}

	if our != nil && competitorKey != "" {
		comp := aggs[competitorKey]
		ourLat := median(our.latencyMedians)
		ourF1 := median(our.f1s)
		compLat := median(comp.latencyMedians)
		compF1 := median(comp.f1s)

		speedup := compLat / ourLat // >1 means we are faster
		var f1Gap float64
		if compF1 > 0 {
			f1Gap = (ourF1 - compF1) / compF1 * 100
		}

		t.Logf("")
		t.Logf("Streaming Mahalanobis : %.0f ns/vec | F1=%.3f", ourLat, ourF1)
		t.Logf("%-22s: %.0f ns/vec | F1=%.3f", competitorKey, compLat, compF1)
		t.Logf("Speedup (comp/ours)   : %.2fx", speedup)
		t.Logf("F1 delta (ours-comp)  : %+.1f%%", f1Gap)

		switch {
		case speedup >= 1.0 && ourF1 >= compF1:
			verdict = fmt.Sprintf("CLEAN-WIN: %.2fx faster AND +%.1f%% F1", speedup, f1Gap)
		case speedup >= 1.0 && f1Gap >= -10:
			verdict = fmt.Sprintf("WIN-ON-SPEED: %.2fx faster, F1 within %.1f%%", speedup, -f1Gap)
		case speedup < 1.0 && ourF1 >= compF1:
			verdict = fmt.Sprintf("WIN-ON-QUALITY: +%.1f%% F1 but %.2fx slower", f1Gap, 1/speedup)
		default:
			verdict = fmt.Sprintf("NARROWED-GAP/LOSS: %.2fx speed, %+.1f%% F1", speedup, f1Gap)
		}
	}

	t.Logf("")
	t.Logf("==========================================================")
	t.Logf("M45 VERDICT: %s", verdict)
	t.Logf("Competitor: %s (%s)", competitorKey, descByMethod[competitorKey])
	t.Logf("==========================================================")

	// --- Write JSON report ---------------------------------------------------
	outDir := filepath.Join("..", "..", "output")
	_ = os.MkdirAll(outDir, 0o755)
	outPath := filepath.Join(outDir, "m45_flip_bench.json")
	envelope := map[string]interface{}{
		"benchmark":   "m45_flip_streaming_vs_sklearn",
		"scenario":    "CorrelationFlip",
		"dimension":   d,
		"seeds":       seedCount,
		"repetitions": repetitions,
		"verdict":     verdict,
		"reports":     reports,
	}
	if b, err := json.MarshalIndent(envelope, "", "  "); err != nil {
		t.Logf("failed to marshal report: %v", err)
	} else if err := os.WriteFile(outPath, b, 0o644); err != nil {
		t.Logf("failed to write report: %v", err)
	} else {
		t.Logf("JSON report written to: %s", outPath)
	}
}

// benchStreamingWithReps runs the streaming detector `reps` times, timing the
// per-vector score+decide path (Update excluded, mirroring the query hot path
// used against the batch competitor). F1/scores are taken from the first rep.
func benchStreamingWithReps(ds *Dataset, d, reps int) streamingResult {
	start, end := ds.TestRange()
	testLabels := ds.Y[start:end]

	res := streamingResult{}
	for r := 0; r < reps; r++ {
		sd := NewStreamingDetectorAdaptive(d, 0.85)
		repScores := make([]float64, len(ds.X))
		repPreds := make([]bool, len(ds.X))

		var totalNs int64
		for i := range ds.X {
			t0 := time.Now()
			score, anom := sd.Observe(ds.X[i]) // causal: model has only seen x[0..i]
			totalNs += time.Since(t0).Nanoseconds()
			repScores[i] = score
			repPreds[i] = anom
		}
		res.perRepLatency = append(res.perRepLatency, float64(totalNs)/float64(len(ds.X)))

		if r == 0 {
			preds := repPreds[start:end]
			res.f1 = computeF1(preds, testLabels)
			res.testScores = append([]float64(nil), repScores[start:end]...)
		}
	}
	return res
}

// benchBatchMahalanobisBaseline is the offline competitor used when Python /
// scikit-learn is unavailable: a batch-covariance Mahalanobis detector that
// trains once on the warmup region and scores the whole test region. Clearly
// labeled as a fallback (NOT sklearn).
func benchBatchMahalanobisBaseline(ds *Dataset, d, reps, warmup int) benchMetric {
	start, end := ds.TestRange()
	testLabels := ds.Y[start:end]

	// Train batch mean + covariance on the clean warmup region.
	mu := make([]float64, d)
	for i := 0; i < warmup; i++ {
		for j := 0; j < d; j++ {
			mu[j] += ds.X[i][j]
		}
	}
	for j := 0; j < d; j++ {
		mu[j] /= float64(warmup)
	}
	cov := make([]float64, d*d)
	for i := 0; i < warmup; i++ {
		for a := 0; a < d; a++ {
			da := ds.X[i][a] - mu[a]
			for b := 0; b < d; b++ {
				cov[a*d+b] += da * (ds.X[i][b] - mu[b])
			}
		}
	}
	inv := 1.0 / float64(warmup-1)
	for k := range cov {
		cov[k] *= inv
	}
	for i := 0; i < d; i++ {
		cov[i*d+i] += 1e-6
	}
	prec, err := invertSymmetricBaseline(cov, d)
	if err != nil {
		// diagonal fallback
		prec = make([]float64, d*d)
		for i := 0; i < d; i++ {
			if cov[i*d+i] > 0 {
				prec[i*d+i] = 1.0 / cov[i*d+i]
			} else {
				prec[i*d+i] = 1.0
			}
		}
	}

	scoreOne := func(x []float64) float64 {
		delta := make([]float64, d)
		for i := 0; i < d; i++ {
			delta[i] = x[i] - mu[i]
		}
		var q float64
		for i := 0; i < d; i++ {
			var s float64
			row := i * d
			for j := 0; j < d; j++ {
				s += prec[row+j] * delta[j]
			}
			q += delta[i] * s
		}
		if q < 0 {
			q = 0
		}
		return q // squared Mahalanobis distance
	}

	var perRep []float64
	testScores := make([]float64, end-start)
	for r := 0; r < reps; r++ {
		var totalNs int64
		for idx := start; idx < end; idx++ {
			t0 := time.Now()
			s := scoreOne(ds.X[idx])
			totalNs += time.Since(t0).Nanoseconds()
			if r == 0 {
				testScores[idx-start] = s
			}
		}
		perRep = append(perRep, float64(totalNs)/float64(end-start))
	}

	// Threshold at the empirical top-anomFraction of test scores (matches the
	// contamination assumption the competitors use).
	thr := quantileThreshold(testScores, 0.90)
	preds := make([]bool, len(testScores))
	for i, s := range testScores {
		preds[i] = s > thr
	}

	return benchMetric{
		Method:          "batch_mahalanobis_baseline",
		Description:     "gonum batch-covariance Mahalanobis retrain (FALLBACK, not sklearn)",
		Dim:             d,
		Samples:         len(testLabels),
		AnomalyRate:     fractionTrue(testLabels),
		AvgLatencyNs:    mean(perRep),
		StdLatencyNs:    stdDev(perRep),
		MedianLatencyNs: median(perRep),
		ThroughputVs:    float64(len(testLabels)) / (mean(perRep) / 1e9),
		F1Score:         computeF1(preds, testLabels),
		AUCROC:          computeAUC(testScores, testLabels),
		Repetitions:     reps,
	}
}

// runSklearnCompetitor executes the Python sklearn competitor and parses its
// JSON output into a benchMetric.
func runSklearnCompetitor(t *testing.T, script, csv string, d, warmup, testSize, reps int) (benchMetric, bool) {
	if _, err := os.Stat(script); os.IsNotExist(err) {
		t.Logf("sklearn script not found at %s", script)
		return benchMetric{}, false
	}
	cmd := exec.Command("python", script,
		"--csv-path", csv,
		"--dim", fmt.Sprintf("%d", d),
		"--warmup", fmt.Sprintf("%d", warmup),
		"--test-size", fmt.Sprintf("%d", testSize),
		"--count", fmt.Sprintf("%d", reps),
		"--mode", "inline",
	)
	var stdout, stderr bytes.Buffer
	cmd.Stdout = &stdout
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		t.Logf("sklearn subprocess error: %v\nstderr: %s", err, stderr.String())
		return benchMetric{}, false
	}

	// The Python script prints human-readable lines before the JSON payload;
	// grab the last non-empty line as the JSON object.
	jsonLine := lastJSONLine(stdout.String())
	if jsonLine == "" {
		t.Logf("no JSON line in sklearn output:\n%s", stdout.String())
		return benchMetric{}, false
	}

	var raw struct {
		Method          string  `json:"method"`
		Description     string  `json:"description"`
		Dimension       int     `json:"dimension"`
		Samples         int     `json:"samples"`
		AnomalyRate     float64 `json:"anomaly_rate"`
		AvgLatencyNs    float64 `json:"avg_latency_ns_per_vec"`
		MedianLatencyNs float64 `json:"median_latency_ns"`
		ThroughputVs    float64 `json:"throughput_vectors_per_sec"`
		F1Score         float64 `json:"f1_score"`
		AUCROC          float64 `json:"auc_roc"`
		Repetitions     int     `json:"repetitions"`
	}
	if err := json.Unmarshal([]byte(jsonLine), &raw); err != nil {
		t.Logf("failed to parse sklearn JSON: %v\nline: %s", err, jsonLine)
		return benchMetric{}, false
	}
	return benchMetric{
		Method:          "sklearn_isolation_forest",
		Description:     raw.Description,
		Dim:             raw.Dimension,
		Samples:         raw.Samples,
		AnomalyRate:     raw.AnomalyRate,
		AvgLatencyNs:    raw.AvgLatencyNs,
		MedianLatencyNs: raw.MedianLatencyNs,
		ThroughputVs:    raw.ThroughputVs,
		F1Score:         raw.F1Score,
		AUCROC:          raw.AUCROC,
		Repetitions:     raw.Repetitions,
	}, true
}

func detectPython(t *testing.T) bool {
	cmd := exec.Command("python", "-c", "import sklearn, numpy")
	if err := cmd.Run(); err != nil {
		t.Logf("python+sklearn not available (%v); will use gonum fallback baseline", err)
		return false
	}
	return true
}

// --- shared helpers --------------------------------------------------------

func saveDatasetToCSV(path string, ds *Dataset) error {
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()

	if _, err := f.WriteString("index,X,label\n"); err != nil {
		return err
	}
	for i := range ds.X {
		if _, err := f.WriteString(fmt.Sprintf("%d,%s,%v\n", i, formatVector(ds.X[i]), ds.Y[i])); err != nil {
			return err
		}
	}
	return nil
}

func formatVector(v []float64) string {
	parts := make([]string, len(v))
	for i := range v {
		parts[i] = fmt.Sprintf("%.6f", v[i])
	}
	out := "[" + parts[0]
	for i := 1; i < len(parts); i++ {
		out += "," + parts[i]
	}
	return out + "]"
}

func mean(xs []float64) float64 {
	if len(xs) == 0 {
		return 0
	}
	var s float64
	for _, x := range xs {
		s += x
	}
	return s / float64(len(xs))
}

func stdDev(xs []float64) float64 {
	if len(xs) <= 1 {
		return 0
	}
	m := mean(xs)
	var sq float64
	for _, x := range xs {
		sq += (x - m) * (x - m)
	}
	return sq / float64(len(xs)-1)
}

func median(xs []float64) float64 {
	if len(xs) == 0 {
		return 0
	}
	cp := append([]float64(nil), xs...)
	sort.Float64s(cp)
	n := len(cp)
	if n%2 == 1 {
		return cp[n/2]
	}
	return (cp[n/2-1] + cp[n/2]) / 2
}

func fractionTrue(bs []bool) float64 {
	if len(bs) == 0 {
		return 0
	}
	c := 0
	for _, b := range bs {
		if b {
			c++
		}
	}
	return float64(c) / float64(len(bs))
}

// quantileThreshold returns the value at quantile q (0..1) of xs.
func quantileThreshold(xs []float64, q float64) float64 {
	if len(xs) == 0 {
		return 0
	}
	cp := append([]float64(nil), xs...)
	sort.Float64s(cp)
	idx := int(q * float64(len(cp)-1))
	if idx < 0 {
		idx = 0
	}
	if idx >= len(cp) {
		idx = len(cp) - 1
	}
	return cp[idx]
}

func computeF1(preds, labels []bool) float64 {
	if len(preds) != len(labels) || len(preds) == 0 {
		return 0
	}
	var tp, fp, fn int
	for i := range preds {
		switch {
		case preds[i] && labels[i]:
			tp++
		case preds[i] && !labels[i]:
			fp++
		case !preds[i] && labels[i]:
			fn++
		}
	}
	var precision, recall float64
	if tp+fp > 0 {
		precision = float64(tp) / float64(tp+fp)
	}
	if tp+fn > 0 {
		recall = float64(tp) / float64(tp+fn)
	}
	if precision+recall > 0 {
		return 2 * precision * recall / (precision + recall)
	}
	return 0
}

// computeAUC computes AUC-ROC via the rank/trapezoidal method. Higher score =
// more anomalous.
func computeAUC(scores []float64, labels []bool) float64 {
	if len(scores) != len(labels) || len(scores) == 0 {
		return 0.5
	}
	type sl struct {
		score float64
		label bool
	}
	items := make([]sl, len(scores))
	for i := range scores {
		items[i] = sl{scores[i], labels[i]}
	}
	sort.Slice(items, func(i, j int) bool { return items[i].score > items[j].score })

	var totalPos, totalNeg int
	for _, it := range items {
		if it.label {
			totalPos++
		} else {
			totalNeg++
		}
	}
	if totalPos == 0 || totalNeg == 0 {
		return 0.5
	}

	var tp, fp int
	var auc, prevTPR, prevFPR float64
	prevScore := items[0].score + 1
	for _, it := range items {
		if it.score != prevScore {
			tpr := float64(tp) / float64(totalPos)
			fpr := float64(fp) / float64(totalNeg)
			auc += (fpr - prevFPR) * (tpr + prevTPR) / 2
			prevTPR, prevFPR = tpr, fpr
			prevScore = it.score
		}
		if it.label {
			tp++
		} else {
			fp++
		}
	}
	tpr := float64(tp) / float64(totalPos)
	fpr := float64(fp) / float64(totalNeg)
	auc += (fpr - prevFPR) * (tpr + prevTPR) / 2
	return auc
}

func lastJSONLine(s string) string {
	lines := bytes.Split([]byte(s), []byte("\n"))
	for i := len(lines) - 1; i >= 0; i-- {
		trimmed := bytes.TrimSpace(lines[i])
		if len(trimmed) > 0 && trimmed[0] == '{' {
			return string(trimmed)
		}
	}
	return ""
}

// invertSymmetricBaseline inverts a symmetric positive-definite matrix via
// Gauss-Jordan elimination (local copy to keep the baseline self-contained).
func invertSymmetricBaseline(m []float64, d int) ([]float64, error) {
	aug := make([]float64, d*2*d)
	for i := 0; i < d; i++ {
		copy(aug[i*2*d:i*2*d+d], m[i*d:(i+1)*d])
		aug[i*2*d+d+i] = 1.0
	}
	for col := 0; col < d; col++ {
		pivot := col
		maxVal := absVal(aug[col*2*d+col])
		for r := col + 1; r < d; r++ {
			if v := absVal(aug[r*2*d+col]); v > maxVal {
				maxVal = v
				pivot = r
			}
		}
		if maxVal < 1e-14 {
			return nil, fmt.Errorf("singular matrix at col %d", col)
		}
		if pivot != col {
			for k := 0; k < 2*d; k++ {
				aug[col*2*d+k], aug[pivot*2*d+k] = aug[pivot*2*d+k], aug[col*2*d+k]
			}
		}
		inv := 1.0 / aug[col*2*d+col]
		for k := 0; k < 2*d; k++ {
			aug[col*2*d+k] *= inv
		}
		for r := 0; r < d; r++ {
			if r == col {
				continue
			}
			factor := aug[r*2*d+col]
			if factor == 0 {
				continue
			}
			for k := 0; k < 2*d; k++ {
				aug[r*2*d+k] -= factor * aug[col*2*d+k]
			}
		}
	}
	out := make([]float64, d*d)
	for i := 0; i < d; i++ {
		copy(out[i*d:(i+1)*d], aug[i*2*d+d:(i+1)*2*d])
	}
	return out, nil
}

func absVal(x float64) float64 {
	if x < 0 {
		return -x
	}
	return x
}
